#!/usr/bin/env python3
"""Regenerate the v15 field adapter from frozen v13/v14 methods."""
import argparse,re,hashlib
from pathlib import Path
a=argparse.ArgumentParser();a.add_argument("--game-dir",type=Path,required=True);p=a.parse_args().game_dir
assert hashlib.sha256((p/"scripts/tactics/player_move_fields.gd").read_bytes()).hexdigest()=="214bc513a0f26d83d56de354101fe020afbfae082c925c8cd7ddad9f99d482f0"
assert hashlib.sha256((p/"scripts/tactics/player_move_seals.gd").read_bytes()).hexdigest()=="1523d6f85d803d9b147932f18930a2bf6576ea26066a7406813286a9b3161c13"
fields=(p/'scripts/tactics/player_move_fields.gd').read_text()
seals=(p/'scripts/tactics/player_move_seals.gd').read_text()
def funcs(src):
 starts=list(re.finditer(r'^static func (\w+)\(',src,re.M));return {x[1]:src[x.start():starts[i+1].start() if i+1<len(starts) else len(src)] for i,x in enumerate(starts)}
functions=funcs(fields);names=['protected_status','prevent_status','attack_view','prepare','reason','factor','raw_damage','enemy_math','entry_damage','on_switch','after_enemy']
code='class_name PlayerMoveAirFields\nextends RefCounted\n## v15 grounding-dependent field adapter. Generated by derive_player_air_fields.py.\n'
for name in names:
 body=functions[name]
 for call in set(functions)-set(names):body=re.sub(r'(?<![.\w])'+call+r'\(',('PlayerMoveAltitude.' if call=='grounded' else 'PlayerMoveFields.')+call+'(',body)
 for const in ['STATUS','TITLES','SIDE','HAZARDS']:body=re.sub(r'(?<![.\w])'+const+r'\b','PlayerMoveFields.'+const,body)
 code+=body
body=funcs(seals)['enemy_math'].replace('static func enemy_math','static func enemy_critical').replace('PlayerMoveFields.factor','factor').replace('PlayerMoveFields.attack_view','attack_view')
code+=body.replace("read(b)","PlayerMoveSeals.read(b)")
(p/'scripts/tactics/player_move_air_fields.gd').write_text(code)
